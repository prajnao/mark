import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fontDir = join(here, "../node_modules/katex/dist/fonts");
const outFile = join(here, "../src/styles/katex-fonts.css");

const FONTS = [
  { file: "KaTeX_Main-Regular", family: "KaTeX_Main", weight: 400, style: "normal" },
  { file: "KaTeX_Main-Bold", family: "KaTeX_Main", weight: 700, style: "normal" },
  { file: "KaTeX_Main-Italic", family: "KaTeX_Main", weight: 400, style: "italic" },
  { file: "KaTeX_Math-Italic", family: "KaTeX_Math", weight: 400, style: "italic" },
  { file: "KaTeX_Math-BoldItalic", family: "KaTeX_Math", weight: 700, style: "italic" },
  { file: "KaTeX_Size1-Regular", family: "KaTeX_Size1", weight: 400, style: "normal" },
  { file: "KaTeX_Size2-Regular", family: "KaTeX_Size2", weight: 400, style: "normal" },
  { file: "KaTeX_Size3-Regular", family: "KaTeX_Size3", weight: 400, style: "normal" },
  { file: "KaTeX_Size4-Regular", family: "KaTeX_Size4", weight: 400, style: "normal" },
  { file: "KaTeX_AMS-Regular", family: "KaTeX_AMS", weight: 400, style: "normal" },
  { file: "KaTeX_Caligraphic-Regular", family: "KaTeX_Caligraphic", weight: 400, style: "normal" },
  { file: "KaTeX_Fraktur-Regular", family: "KaTeX_Fraktur", weight: 400, style: "normal" },
  { file: "KaTeX_SansSerif-Regular", family: "KaTeX_SansSerif", weight: 400, style: "normal" },
  { file: "KaTeX_Script-Regular", family: "KaTeX_Script", weight: 400, style: "normal" },
  { file: "KaTeX_Typewriter-Regular", family: "KaTeX_Typewriter", weight: 400, style: "normal" },
];

let css = "/* Generated by build-katex-fonts.mjs. Do not edit. */\n";
let bytes = 0;

for (const font of FONTS) {
  const data = readFileSync(join(fontDir, `${font.file}.woff2`)).toString("base64");
  bytes += data.length;

  css += `@font-face{font-family:"${font.family}";`;
  css += `font-style:${font.style};font-weight:${font.weight};`;
  css += `src:url(data:font/woff2;base64,${data}) format("woff2");`;
  css += `font-display:block}\n`;
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, css);

